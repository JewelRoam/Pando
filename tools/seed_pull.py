#!/usr/bin/env python3
"""Pull sealed offers and keep them. Do not unwrap, and do not start a model."""
from __future__ import annotations

import argparse
import io
import json
import socket
import sys
import tarfile
import tempfile
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

# The same list-in-a-file reader the code updater uses, so "which peers does
# this node have" is written in one format and parsed by one function.
from tools.code_sync import source_file, source_list  # noqa: E402


def _seed():
    import importlib.util
    tool = Path(__file__).resolve().parent / "seed.py"
    spec = importlib.util.spec_from_file_location("pandosi_seed_pull_tool", tool)
    if spec is None or spec.loader is None:
        raise RuntimeError("seed tool is missing")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _request(url: str, token: str, method: str = "GET", body: bytes | None = None):
    req = urllib.request.Request(url, data=body, method=method)
    req.add_header("Authorization", f"Bearer {token}")
    if body is not None:
        req.add_header("Content-Type", "application/json")
    with urllib.request.urlopen(req, timeout=20) as response:
        return response.read()


def _extract(packed: bytes, dest: Path, seed) -> bool:
    """Unpack the offered tar. A tar that rotted on the way is not an exception.

    ``tarfile`` raises a truncated archive only while the members are being
    walked, so the guard has to cover the loop and not just the open. A
    truncated offer used to raise ``ReadError`` out of ``pull_once`` and stop
    the whole round, so every offer behind it in sort order went unfetched.
    That is a latent failure, not an observed one: measured 2026-10-19, all
    53 offers on the mac shelf served 200 and judged clean, so nothing was
    actually being starved there. The path still had to be closed -- one
    rotted byte would have been enough, and the failure is silent.
    """
    dest.mkdir(parents=True, exist_ok=True)
    try:
        archive = tarfile.open(fileobj=io.BytesIO(packed), mode="r:")
    except tarfile.TarError:
        return False
    try:
        for member in archive.getmembers():
            if not seed._rel_is_safe(member.name) or not member.isfile():
                return False
            target = dest / member.name
            target.parent.mkdir(parents=True, exist_ok=True)
            source = archive.extractfile(member)
            if source is None:
                return False
            target.write_bytes(source.read())
    except (tarfile.TarError, OSError):
        return False
    return (dest / seed.MANIFEST).is_file()


def pick_source(bases, token: str) -> tuple[str, list[str], dict]:
    """The first source whose shelf answers, and every source tried.

    A round has to stay on one shelf: the listing it read and the bytes it
    fetches have to come from the same place, or a node acks an offer it
    never received. So the choice is made once, here, and the round does not
    hop between sources afterwards.

    Nothing answers is an error, not an empty round. An empty round is
    indistinguishable from a healthy, up-to-date landing point, and this
    exact ambiguity is what hid the Mac's shelf going unpulled for hours on
    2026-10-19 while every node's log showed a live process.
    """
    tried: list[str] = []
    for candidate in bases:
        url = str(candidate or "").rstrip("/")
        if not url or url in tried:
            continue
        tried.append(url)
        try:
            listing = json.loads(_request(f"{url}/offers", token).decode("utf-8"))
        except Exception:  # noqa: BLE001 - a dead source is the next one's turn
            continue
        return url, tried, listing
    raise urllib.error.URLError(
        "no source answered /offers; tried " + ", ".join(tried or ["(none)"]))


def pull_once(base: str, token: str, inbox: Path, ledger: Path | None = None,
              fallbacks=None, node_id: str = "") -> dict:
    """Download every sealed offer and keep the ones that still verify."""
    seed = _seed()
    # A receipt only means something when it names the receiver.  A literal
    # ``by: pull`` was generated by every node, so 17 acks could not answer
    # whether the Mac shelf had reached Windows or Pi5.  The hostname is a
    # usable default for a one-off run; resident units pass a stable node id.
    by = (node_id or socket.gethostname()).strip()[:80]
    base, tried, listing = pick_source([base, *(fallbacks or [])], token)
    copied = []
    refused = []
    duplicates = []
    for row in listing.get("offers") or []:
        proposal_id = str(row.get("proposal_id") or "")
        if seed._INBOX_NAME.fullmatch(proposal_id) is None:
            refused.append(proposal_id or "?")
            continue
        try:
            packed = _request(f"{base}/offer/{proposal_id}.tar", token)
        except urllib.error.HTTPError:
            # The peer listed an offer it will not hand over. That is one bad
            # offer, not a dead mailbox: record it and keep pulling the rest.
            refused.append(proposal_id)
            continue
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / "bundle"
            if not _extract(packed, src, seed):
                refused.append(proposal_id)
                continue
            kept = seed.receive_bundle(src, inbox, ledger=ledger)
        if kept.get("reason") == "already-received":
            # The bytes verify and the delivery is complete; the inbox simply
            # holds this bundle already. Counted, not acked -- nothing prunes
            # the sender's shelf, so a duplicate offer would sit there unacked
            # anyway. Skipping it silently made this invisible, and the mac
            # shelf shows exactly why that matters: measured 2026-10-19 it
            # advertised 53 offers carrying only 17 distinct bundles, and all
            # 17 had landed (17 inbox dirs, 17 receive-ledger rows, 17 acks).
            # The other 36 were the same bundle staged again -- one of them 20
            # times -- not 36 lost deliveries. Without this counter the old
            # round printed "copied: [], refused: []" and could not be told
            # apart from a healthy, up-to-date landing point.
            duplicates.append(proposal_id)
            continue
        if not kept.get("copied"):
            refused.append(proposal_id)
            continue
        ack = json.dumps({"by": by}).encode("utf-8")
        _request(f"{base}/offer/{proposal_id}/ack", token, method="POST", body=ack)
        copied.append(proposal_id)
    return {"copied": copied, "refused": refused, "duplicate": duplicates,
            "via": base, "tried": tried if len(tried) > 1 else [],
            "unwrapped": False, "started_model": False}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--from", dest="bases", action="append",
                        required=True,
                        help="outbox base URL; repeat for fallbacks, tried "
                             "in order")
    parser.add_argument("--from-file", default="",
                        help="file of outbox base URLs, one per line; "
                             "appended after repeated --from. Put the "
                             "addresses here so a peer that moves is a file "
                             "edit, not a service-definition edit on every "
                             "host.")
    parser.add_argument("--token-file", required=True)
    parser.add_argument("--inbox", default="~/.pandosi/inbox")
    parser.add_argument("--ledger", default="")
    parser.add_argument("--node-id", default="",
                        help="stable receiver identity stored in the ACK; "
                             "defaults to the hostname for one-off runs")
    parser.add_argument("--once", action="store_true")
    args = parser.parse_args(argv)
    token = Path(args.token_file).expanduser().read_text(encoding="utf-8").strip()
    # `--from-file` may be empty: then the conventional names are probed, so
    # the same unit definition serves a host whose state directory is
    # `~/.pandosi`, `~/.pando` or `D:\PandoRSI\models`.
    bases = list(args.bases) + source_list(
        source_file(args.from_file, kind="seed"))
    ledger = Path(args.ledger).expanduser() if args.ledger else None
    base, fallbacks = bases[0], bases[1:]

    def run(announce: bool) -> int:
        result = pull_once(base, token, Path(args.inbox), ledger,
                           fallbacks=fallbacks, node_id=args.node_id)
        if (announce or result["copied"] or result["refused"]
                or result["duplicate"]):
            print(json.dumps(result, ensure_ascii=False, sort_keys=True), flush=True)
        return 0

    if args.once:
        return run(True)
    import time
    while True:
        try:
            run(False)
        except Exception as exc:  # noqa: BLE001 - a pull failure must not kill the loop
            print(json.dumps({"error": str(exc)[:200]}, ensure_ascii=False), flush=True)
        time.sleep(60)


if __name__ == "__main__":
    raise SystemExit(main())
